/**
 * @brief Resolves what to actually reflect over: t itself, or - if t is a
 * jeson::Field<Name, Struct, true> (the struct-inheriting Field
 * specialization; see field.hpp) - the base Struct it inherits.
 *
 * Field<Name, Struct, true> declares a JesonReflectAs type alias
 * specifically so this function can detect it via a `requires` clause and
 * upcast; plain user structs never declare that alias, so this is a no-op
 * for them and just returns t unchanged.
 *
 * @tparam T The type being reflected over (a plain struct, or a Field<> wrapper).
 * @return A reference to the type that should actually be decomposed.
 */
template <typename T>
constexpr auto& reflectionTarget(T& t) {
    if constexpr (requires { typename T::JesonReflectAs; }) {
        return static_cast<typename T::JesonReflectAs&>(t);
    } else {
        return t;
    }
}

/**
 * @brief The library's entire reflection mechanism: given any jeson
 * struct (or Field<> wrapping one), returns a std::tuple of references to
 * its members, in declaration order.
 *
 * @tparam T A plain aggregate struct, or a Field<Name, Struct, true> wrapping one.
 * @return std::tuple<Member1&, Member2&, ...> - mutating through this tuple
 * mutates the original object, since these are references, not copies.
 */
template <typename T>
auto tie_members(T& t) {
    auto& real               = reflectionTarget(t);
    using Real                = std::remove_reference_t<decltype(real)>;
    constexpr std::size_t n  = count_fields<Real>();
    return tie_fields_n(real, std::integral_constant<std::size_t, n>{});
}

/// True for any plain class/struct type jeson can reflect over (has no
/// user-declared constructors, no private members, no virtual functions -
/// the standard definition of a C++ aggregate). False for containers,
/// strings, enums, and jeson's own wrapper types (Validator/Required),
/// which all have user-declared constructors and are handled as leaf
/// values instead - see field.hpp.
template <typename T>
inline constexpr bool is_reflectable_aggregate_v = std::is_class_v<T> && std::is_aggregate_v<T>;

